"""Write a codebook for the data to ``docs/codebook.md``.

It documents the flat tables (from ``datapackage.json``), the relational tables loaded into SQLite
(from the schema files in ``src-data/datapackage/``) and the code tables (the values of the coded
variables, from ``data/relational/enum_*.csv``).
"""

import csv
import json
from pathlib import Path
from typing import Any

import yaml

SCHEMA_DIR = Path("src-data/datapackage")
RELATIONAL = Path("data/relational")
OUTPUT = Path("docs/codebook.md")


def clean(text: str | None) -> str:
    """Collapse whitespace and escape pipes, so the text fits in a table cell."""
    return " ".join((text or "").split()).replace("|", "\\|")


def load_yaml(path: Path) -> Any:
    """Read a YAML file."""
    with path.open() as f:
        return yaml.safe_load(f)


def column_table(fields: list[dict[str, Any]], key: str) -> list[str]:
    """Return the Markdown table of a table's columns; ``key`` is the field's name key."""
    lines: list[str] = ["| Column | Type | Description |", "|---|---|---|"]
    lines += [
        f"| `{field[key]}` | {field['type']} | {clean(field.get('description'))} |"
        for field in fields
    ]
    return lines


def flat_section() -> list[str]:
    """Document the flat tables."""
    package = json.loads(Path("datapackage.json").read_text())
    lines: list[str] = [
        "## Flat tables",
        "",
        "For analysis. Each is `data/flat/<name>.csv` and `data/flat/<name>.parquet`; the CSVs are",
        "described by `datapackage.json`. Missing values are empty.",
        "",
    ]
    for resource in package["resources"]:
        lines += [f"### `{resource['name']}`", "", clean(resource["description"]), ""]
        lines += [*column_table(resource["schema"]["fields"], "name"), ""]
    return lines


def relational_section() -> list[str]:
    """Document the relational tables."""
    lines: list[str] = [
        "## Relational tables",
        "",
        "The tables loaded into `cdb90.sqlite3`; one CSV per table in `data/relational/`.",
        "`isqno` is the battle's sequence number in CDB90 and links the tables.",
        "",
    ]
    for path in sorted((SCHEMA_DIR / "resources").glob("*.yaml")):
        resource = load_yaml(path)
        lines += [f"### `{Path(resource['path']).stem}`", ""]
        if resource.get("description"):
            lines += [clean(resource["description"]), ""]
        lines += [*column_table(resource["schema"]["fields"], "id"), ""]
    return lines


def codes_section() -> list[str]:
    """Document the code tables."""
    lines: list[str] = [
        "## Code tables",
        "",
        "The values of the coded variables. Each is a table `enum_<name>` in SQLite with a `value`",
        "and a `description`; the description says which variable uses the codes.",
        "",
    ]
    for name, enum in load_yaml(SCHEMA_DIR / "enum_tables.yaml").items():
        lines += [f"### `enum_{name}`", "", clean(enum["description"]), ""]
        lines += ["| Value | Meaning |", "|---|---|"]
        with (RELATIONAL / f"enum_{name}.csv").open(newline="", encoding="utf-8") as f:
            lines += [
                f"| `{row['value']}` | {clean(row['description'])} |" for row in csv.DictReader(f)
            ]
        lines.append("")
    return lines


def main() -> None:
    """Write the codebook."""
    lines: list[str] = [
        "# CDB90 codebook",
        "",
        "Generated by `scripts/codebook.py` from the table schemas; do not edit by hand.",
        "The original documentation of CDB90 is `src-data/M000121/README.TXT`.",
        "",
        *flat_section(),
        *relational_section(),
        *codes_section(),
    ]
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
